    def test_entries_can_be_queried_by_date_range(
        self, api_client: TestClient, admin_headers: dict[str, str], main_database: str
    ) -> None:
        """The date rule is not decoration: reports filter on the stored instant."""
        world = build_world(api_client, admin_headers, main_database)
        old, recent = at_utc(days_ago=10), at_utc(hours_ago=2)

        async def scenario(service):
            first = await service.create_journal_entry(
                **manual_entry(  # type: ignore[arg-type]
                    world, reference_id=uuid.uuid4(), transaction_date=old
                )
            )
            second = await service.create_journal_entry(
                **manual_entry(  # type: ignore[arg-type]
                    world, reference_id=uuid.uuid4(), transaction_date=recent
                )
            )
            # A window only this posting can fall into: the branch is shared with every
            # other scenario in the run, so a five-day window would be dominated by their
            # "now" postings and the page would not be about this test at all.
            windowed, total = await service.list_journal_entries(
                actor=world.head_actor,
                branch_id=world.branch_id,
                from_=at_utc(hours_ago=3),
                to=at_utc(hours_ago=1),
                limit=200,
            )
            return first, second, {view.id for view in windowed}, total

        first, second, visible, total = run_scenario(main_database, scenario)
        assert first.id not in visible
        assert second.id in visible
        assert total >= 1
        assert total == len(visible), "the page was truncated by the limit, not by the filter"


