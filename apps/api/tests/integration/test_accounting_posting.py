"""Phase 4 — posting the ledger: the balance proof, validation and atomicity.

Every test here goes through :class:`AccountingService` (the only writer, PART 46) against
the real migrated, seeded database, and then reads the result back with SQL to check what
was actually *stored* rather than what the service says it stored. That distinction is the
whole point of a financial test suite: a service that reports a balanced entry while
writing an unbalanced one would pass a test that only inspected its return value.

Covered here: the balanced/unbalanced matrix, multi-line entries, decimal precision at the
stored scale, accounting dates, reference/document rules, account and currency validation,
branch validation, and transaction atomicity (a failure leaves nothing behind — no entry,
no lines, no cache row, no audit row, no idempotency row).
"""

