def manual_entry(world: World, **overrides: object) -> dict[str, object]:
    """The arguments of a two-line manual adjustment, overridable per test.

    A manual adjustment is the one reference type that may omit its document id, which
    makes it the right vehicle for testing the posting rules themselves without inventing a
    business document.
    """
    arguments: dict[str, object] = {
        "reference_type": "MANUAL_ADJUSTMENT",
        "reference_id": uuid.uuid4(),
        "lines": [
            line(world.account("cash_afn"), debit="1000", currency_id=world.base.id),
            line(world.account("capital"), credit="1000", currency_id=world.base.id),
        ],
        "actor": world.head_actor,
        "branch_id": world.branch_id,
        "description": "Phase 4 posting suite",
    }
    arguments.update(overrides)
    return arguments


class TestBalancedPosting:
    """The happy path, verified in the database and not only in the return value."""

    def test_a_balanced_entry_is_stored_exactly_as_posted(
        self, api_client: TestClient, admin_headers: dict[str, str], main_database: str
    ) -> None:
        world = build_world(api_client, admin_headers, main_database)
        reference_id = uuid.uuid4()

        async def scenario(service):
            return await service.create_journal_entry(
                **manual_entry(  # type: ignore[arg-type]
                    world,
                    reference_id=reference_id,
                    description="Opening the till",
                    transaction_date=at_utc(minutes_ago=30),
                )
            )

        view = run_scenario(main_database, scenario)

        assert view.is_balanced is True
        assert view.total_debit == Decimal("1000")
        assert view.total_credit == Decimal("1000")
        assert view.line_count == 2
        assert view.reference_type == "MANUAL_ADJUSTMENT"
        assert view.reference_id == reference_id
        assert view.branch_id == world.branch_id
        assert view.branch_code == world.branch_code
        assert view.created_by == world.head_user_id
        assert view.created_by_username == "admin"
        assert view.transaction_date.astimezone(dt.UTC).year == dt.datetime.now(tz=dt.UTC).year

        # ... and in the database
        stored = entry_row(main_database, view.id)
        assert stored["reference_id"] == reference_id
        assert stored["branch_id"] == world.branch_id
        assert stored["description"] == "Opening the till"
        rows = ledger_rows(main_database, view.id)
        assert len(rows) == 2
        debit_row = next(row for row in rows if row["account_id"] == world.account("cash_afn"))
        credit_row = next(row for row in rows if row["account_id"] == world.account("capital"))
        assert debit_row["debit"] == Decimal("1000.0000000000")
        assert debit_row["credit"] == Decimal("0E-10")
        assert credit_row["credit"] == Decimal("1000.0000000000")
        # ``foreign_amount`` is generated by PostgreSQL from the pair and the rate.
        assert debit_row["foreign_amount"] == Decimal("1000.0000000000")
        assert credit_row["exchange_rate"] == Decimal("1.0000000000")

